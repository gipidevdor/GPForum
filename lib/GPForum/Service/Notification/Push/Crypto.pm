package GPForum::Service::Notification::Push::Crypto;

use Mojo::Base -base, -signatures;
use v5.40;
use Const::Fast;
use Digest::SHA          qw(sha256_hex);
use Crypt::AuthEnc::GCM  qw(gcm_encrypt_authenticate gcm_decrypt_verify);
use Crypt::JWT           qw(encode_jwt);
use Crypt::KeyDerivation qw(hkdf);
use Crypt::PK::ECC;
use Crypt::URandom qw(urandom);
use MIME::Base64   qw(encode_base64url decode_base64url);
use Mojo::JSON     qw(encode_json decode_json);
use GPForum::X::Argument;

our $VERSION = '0.001';
const my $POINT_FORMAT        => 4;
const my $ENVELOPE_FORMAT     => 1;
const my $FINAL_RECORD        => 2;
const my $PUBLIC_BYTES        => 65;
const my $AUTH_BYTES          => 16;
const my $KEY_BYTES           => 32;
const my $NONCE_BYTES         => 12;
const my $TAG_BYTES           => 16;
const my $RECORD_BYTES        => 4096;
const my $PAYLOAD_BYTES       => 1024;
const my $ENVELOPE_BYTES      => 16_384;
const my $KEY_ID_DIGITS       => 16;
const my $MAX_RECEIVER_POINTS => 256;
const my $MAX_CACHED_TOKENS   => 128;
const my $TOKEN_SECONDS       => 900;
const my $REFRESH_SECONDS     => 60;

has receiver_points => sub { return {}; };
has receiver_order  => sub { return []; };
has tokens          => sub { return {}; };

sub unbase64 ( $, $value, $length ) {
    if (  !defined $value
        || ref $value
        || $value !~ /\A[[:alnum:]_-]+\z/amsx )
    {
        _invalid();
    }
    my $bytes = decode_base64url($value);
    if ( length($bytes) != $length
        || encode_base64url($bytes) ne $value )
    {
        _invalid();
    }
    return $bytes;
}

sub receiver ( $self, $keys ) {
    if ( ref $keys ne 'HASH' ) { _invalid(); }
    my $public = $self->unbase64( $keys->{p256dh}, $PUBLIC_BYTES );
    my $auth   = $self->unbase64( $keys->{auth},   $AUTH_BYTES );
    if ( ord($public) != $POINT_FORMAT ) { _invalid(); }

    # Only the validated public curve point is cached. Authentication
    # secrets are checked on every call; ECDH sender keys and salts are
    # always freshly generated by encrypt. The cache has a fixed bound.
    my $fingerprint = sha256_hex($public);
    my $key         = $self->receiver_points->{$fingerprint};
    if ( !$key ) {
        try {
            $key = Crypt::PK::ECC->new->import_key_raw( $public, 'prime256v1' );
        }
        catch ($error) { _invalid(); };
        if ( $key->is_private || $key->export_key_raw('public') ne $public ) {
            _invalid();
        }
        if ( @{ $self->receiver_order } >= $MAX_RECEIVER_POINTS ) {
            my $oldest = shift @{ $self->receiver_order };
            delete $self->receiver_points->{$oldest};
        }
        push @{ $self->receiver_order }, $fingerprint;
        $self->receiver_points->{$fingerprint} = $key;
    }
    return { key => $key, public => $public, auth => $auth };
}

# RFC 8291 section 3.4 and RFC 8188 single final record. The optional
# material is only for published interoperability vectors; callers sending
# notifications never supply it. CryptX validates the imported curve point.
sub encrypt ( $self, $keys, $plaintext, $material = {} ) {
    if ( !defined $plaintext || length($plaintext) > $PAYLOAD_BYTES ) {
        _invalid();
    }
    my $receiver = $self->receiver($keys);
    my $sender   = $material->{sender}
      // Crypt::PK::ECC->new->generate_key('prime256v1');
    my $salt = $material->{salt} // urandom($AUTH_BYTES);
    if ( length($salt) != $AUTH_BYTES ) { _invalid(); }
    my $public = $sender->export_key_raw('public');
    my $secret = $sender->shared_secret( $receiver->{key} );
    my $info   = "WebPush: info\0" . $receiver->{public} . $public;
    my $ikm = hkdf( $secret, $receiver->{auth}, 'SHA256', $KEY_BYTES, $info );
    my $cek = hkdf( $ikm, $salt, 'SHA256', $AUTH_BYTES,
        "Content-Encoding: aes128gcm\0" );
    my $nonce =
      hkdf( $ikm, $salt, 'SHA256', $NONCE_BYTES, "Content-Encoding: nonce\0" );
    my $final_plaintext = $plaintext . chr $FINAL_RECORD;
    my ( $cipher, $tag ) =
      gcm_encrypt_authenticate( 'AES', $cek, $nonce, q{}, $final_plaintext );
    return
        $salt
      . pack( 'NC', $RECORD_BYTES, $PUBLIC_BYTES )
      . $public
      . $cipher
      . $tag;
}

sub validate_signing_key ( $self, $key_id, $private ) {
    my $key = Crypt::PK::ECC->new->import_key_raw(
        $self->unbase64( $private, $KEY_BYTES ), 'prime256v1' );
    my $expected_id =
      substr sha256_hex( encode_base64url( $key->export_key_raw('public') ) ),
      0, $KEY_ID_DIGITS;
    if ( $key_id ne $expected_id ) { _invalid(); }
    return $key;
}

sub authorization ( $self, $origin, $key_id, $private, $contact ) {
    my $cache_key = "$key_id:$origin";
    my $cached    = $self->tokens->{$cache_key};
    return $cached->{value}
      if $cached && $cached->{expires} > time + $REFRESH_SECONDS;
    my $key = $self->validate_signing_key( $key_id, $private );
    if ( keys %{ $self->tokens } >= $MAX_CACHED_TOKENS ) {
        my ($oldest) =
          sort { $self->tokens->{$a}{expires} <=> $self->tokens->{$b}{expires} }
          keys %{ $self->tokens };
        delete $self->tokens->{$oldest};
    }
    my $expires = time + $TOKEN_SECONDS;
    my $token   = encode_jwt(
        payload => { aud => $origin, exp => $expires, sub => $contact },
        key     => $key,
        alg     => 'ES256'
    );
    my $value =
        'vapid t='
      . $token . ', k='
      . encode_base64url( $key->export_key_raw('public') );
    $self->tokens->{$cache_key} = { expires => $expires, value => $value };
    return $value;
}

# Versioned AES-256-GCM envelopes; purpose and owner are authenticated too,
# so swapping the ciphertext of two database rows cannot swap a receiver.
sub seal ( $, $key, $context, $document ) {
    if ( length($key) != $KEY_BYTES ) { _invalid(); }
    my $nonce = urandom($NONCE_BYTES);
    my ( $cipher, $tag ) = gcm_encrypt_authenticate( 'AES', $key, $nonce,
        "GPForum.push.v1:$context", encode_json($document) );
    return encode_base64url( chr($ENVELOPE_FORMAT) . $nonce . $tag . $cipher );
}

sub unseal ( $, $key, $context, $envelope ) {
    if (  !defined $envelope
        || ref $envelope
        || length($envelope) > $ENVELOPE_BYTES
        || $envelope !~ /\A[[:alnum:]_-]+\z/amsx )
    {
        _invalid();
    }
    my $bytes = decode_base64url($envelope);
    if (   length($key) != $KEY_BYTES
        || length($bytes) < 1 + $NONCE_BYTES + $TAG_BYTES
        || ord($bytes) != $ENVELOPE_FORMAT )
    {
        _invalid();
    }
    my $nonce  = substr $bytes, 1, $NONCE_BYTES;
    my $tag    = substr $bytes, 1 + $NONCE_BYTES, $TAG_BYTES;
    my $cipher = substr $bytes, 1 + $NONCE_BYTES + $TAG_BYTES;
    my $plain  = gcm_decrypt_verify( 'AES', $key, $nonce,
        "GPForum.push.v1:$context", $cipher, $tag );
    if ( !defined $plain ) { _invalid(); }
    return decode_json($plain);
}

sub _invalid {
    GPForum::X::Argument->throw(
        message => 'invalid push cryptographic material' );
}

1;

__END__

=head1 NAME

GPForum::Service::Notification::Push::Crypto - RFC 8291 payload encryption, VAPID and authenticated database envelopes.

=head1 DESCRIPTION

RFC 8291 payload encryption, VAPID and authenticated database envelopes. See docs/ops/web-push.md for deployment and lifecycle guarantees.

=head1 SUBROUTINES/METHODS

=head2 unbase64

Decode a canonical base64url string of exactly the requested byte length, or raise X::Argument.

=head2 receiver

Validate the 65-byte uncompressed P-256 point and 16-byte authentication secret with CryptX.

=head2 encrypt

Return the aes128gcm wire body. Production calls generate a fresh ECDH key and salt. Optional material is for RFC test vectors.

=head2 validate_signing_key

Validate a private P-256 signing key and its public identity before claiming jobs. Returns the CryptX key object.

=head2 authorization

Return a short-lived ES256 VAPID authorization, cached by signing identity and exact HTTPS origin.

=head2 seal

Encrypt a JSON document with AES-256-GCM, authenticating its owner and purpose as additional data.

=head2 unseal

Authenticate and decrypt a stored envelope. A changed owner, purpose, key or ciphertext is refused.

=head1 VERSION

Version 0.001.

=head1 SYNOPSIS

    my $service = GPForum::Service::Notification::Push::Crypto->new();

=head1 DIAGNOSTICS

Invalid input fails closed. Transport failures are bounded and reported without receiver capability URLs or key material.

=head1 CONFIGURATION AND ENVIRONMENT

Dependencies and validated settings are supplied by the composition layer. See docs/ops/web-push.md.

=head1 DEPENDENCIES

CryptX supplies cryptographic primitives; Mojolicious supplies asynchronous HTTPS; versioned PostgreSQL API functions own persistence.

=head1 INCOMPATIBILITIES

Private key files require a persistent service account and restrictive filesystem permissions.

=head1 BUGS AND LIMITATIONS

A provider acceptance does not guarantee display. An already accepted notification cannot be recalled.

